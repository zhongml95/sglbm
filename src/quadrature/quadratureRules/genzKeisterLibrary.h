    static void getPointsAndWeights(std::size_t level, std::vector<T>& pts, std::vector<T>& wts) {
        const auto& pMap = points();
        const auto& wMap = weights();

        if (pMap.count(level) == 0 || wMap.count(level) == 0) {
            throw std::runtime_error("Unsupported Genz-Keister level: " + std::to_string(level));
        }

        const std::vector<T>& posPts = pMap.at(level);
        const std::vector<T>& posWts = wMap.at(level);

        pts.clear();
        wts.clear();

        // Add negative nodes and weights (excluding zero)
        for (std::size_t i = 0; i < posPts.size(); ++i) {
            if (std::abs(posPts[i]) > std::numeric_limits<T>::epsilon()) {
                pts.push_back(-posPts[i]);
                wts.push_back(posWts[i]);
            }
        }

        // Add positive nodes and weights
        pts.insert(pts.end(), posPts.begin(), posPts.end());
        wts.insert(wts.end(), posWts.begin(), posWts.end());

        // Sort both points and weights together
        std::vector<std::pair<T, T>> zipped;
        zipped.reserve(pts.size());
        for (std::size_t i = 0; i < pts.size(); ++i) {
            zipped.emplace_back(pts[i], wts[i]);
        }

        std::sort(zipped.begin(), zipped.end(), [](const auto& a, const auto& b) {
            return a.first < b.first;
        });

        for (std::size_t i = 0; i < pts.size(); ++i) {
            pts[i] = zipped[i].first;
            wts[i] = zipped[i].second;
        }

        for (auto& x : pts)         // scale nodes
            x *= std::sqrt(2.0);

        T w_sum = std::accumulate(wts.begin(), wts.end(), T(0));
        for (auto& w : wts)        // normalise weights
            w /= w_sum;

    }

